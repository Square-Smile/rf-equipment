#!/usr/bin/env node
// build-list.mjs — human-readable views of v1/rf-equipment.json (stdlib only).
//
// Usage:
//   node scripts/build-list.mjs                 # write EQUIPMENT.md
//   node scripts/build-list.mjs --check         # fail if EQUIPMENT.md is out of date (CI)
//   node scripts/build-list.mjs --html <path>   # write the searchable Pages index.html
//
// EQUIPMENT.md is generated: never edit it by hand. Edit v1/rf-equipment.json,
// then run this script and commit both.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("..", import.meta.url);
const pathOf = (rel) => fileURLToPath(new URL(rel, root));
const JSON_URL = "https://square-smile.github.io/rf-equipment/v1/rf-equipment.json";
const PAGE_URL = "https://square-smile.github.io/rf-equipment/";
const REPO_URL = "https://github.com/Square-Smile/rf-equipment";

const pkg = JSON.parse(readFileSync(pathOf("v1/rf-equipment.json"), "utf8"));
const TYPES = { mic: "Mic", iem: "IEM", wmas: "WMAS", radio: "Radio", advisory: "Note" };

const num = (v) => String(Number(v.toFixed(3)));
const range = (r) => r.deviceType === "advisory" ? "" :
  (Array.isArray(r.segments) ? r.segments : [[r.freqStart, r.freqEnd]]).map(([a, b]) => num(a) + "–" + num(b)).join(" + ");
const step = (r) => (r.stepKhz ? num(r.stepKhz) + " kHz" : "");
const src = (r) => (r.source && pkg.sources[r.source]) || null;

// Brands A–Z (ignoring a leading "the "), rows in file order inside a brand.
const sortKey = (b) => b.replace(/^the\s+/i, "").toLowerCase();
const brands = [...new Set(pkg.manufacturers.map((r) => r.brand))].sort((a, b) => sortKey(a).localeCompare(sortKey(b)));
const rowsOf = (b) => pkg.manufacturers.filter((r) => r.brand === b);
const ranged = pkg.manufacturers.filter((r) => r.deviceType !== "advisory");

// GitHub heading anchors: lowercase, drop punctuation, spaces to hyphens.
const slug = (s) => s.toLowerCase().replace(/[^\p{L}\p{N} _-]/gu, "").replace(/ /g, "-");

function markdown() {
  const md = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
  const out = [];
  out.push("# Wireless equipment list", "");
  out.push("<!-- Generated by scripts/build-list.mjs from v1/rf-equipment.json. Do not edit by hand. -->", "");
  out.push(`List version **${pkg.version}** · ${ranged.length} frequency bands and ${pkg.manufacturers.length - ranged.length} notes from ${brands.length} brands · ${Object.keys(pkg.sources).length} manufacturer documents cited.`, "");
  out.push("Wireless microphone, in-ear monitor (IEM) and WMAS frequency ranges as published by the manufacturers. " +
    "Every range links to the manufacturer document it comes from. Used by KlarFunk and FreqSense for frequency coordination.", "");
  out.push(`- Searchable version: ${PAGE_URL}`);
  out.push(`- Machine-readable: [v1/rf-equipment.json](${JSON_URL}) (schema in [README.md](README.md))`);
  out.push(`- Found an error or missing gear? [Open an issue](${REPO_URL}/issues/new) with a link to the manufacturer's own document (spec sheet, manual or frequency list). Dealer pages can't be used as sources.`);
  out.push("- A range is what the hardware can tune. Whether you may use it depends on your country: check your regulator (in Germany, the BNetzA general assignment).", "");
  out.push("**Brands:** " + brands.map((b) => `[${b}](#${slug(b)}) (${rowsOf(b).length})`).join(" · "), "");
  for (const b of brands) {
    const rows = rowsOf(b);
    const bands = rows.filter((r) => r.deviceType !== "advisory");
    const notes = rows.filter((r) => r.deviceType === "advisory");
    out.push(`## ${b}`, "");
    if (bands.length) {
      out.push("| Series | Band | MHz | Type | Step | Source | Note |", "|---|---|---|---|---|---|---|");
      for (const r of bands) {
        const s = src(r);
        out.push(`| ${md(r.series)} | ${md(r.band)} | ${range(r)} | ${TYPES[r.deviceType]} | ${step(r)} | ${s ? `[${md(s.title)}](${s.url})` : ""} | ${md(r.note)} |`);
      }
      out.push("");
    }
    for (const r of notes) {
      const s = src(r);
      out.push(`- **${md(r.series.replace(/\s*\(Note\)$/, "").replace(/^Note$/, b))}:** ${md(r.note)}${s ? ` ([source](${s.url}))` : ""}`);
    }
    if (notes.length) out.push("");
  }
  const systems = Object.entries(pkg.presetTables)
    .map(([sys, bands]) => [sys, Object.entries(bands).filter(([, g]) => Object.values(g).some((c) => Object.keys(c).length))])
    .filter(([, bands]) => bands.length);
  out.push("## Group / channel preset tables", "");
  out.push("Factory group and channel tables, transcribed from the manufacturers' frequency lists. The MHz values are in the JSON (`presetTables`).", "");
  out.push("| System | Band | Groups | Channels |", "|---|---|---|---|");
  for (const [sys, bands] of systems) for (const [band, groups] of bands) {
    const chans = Object.values(groups).reduce((n, c) => n + Object.values(c).filter((v) => v !== null).length, 0);
    out.push(`| ${md(sys)} | ${md(band)} | ${Object.keys(groups).length} | ${chans} |`);
  }
  out.push("");
  if (pkg.legacyBands.length) {
    out.push("<details><summary>Removed band names (kept so saved equipment still loads)</summary>", "");
    for (const r of pkg.legacyBands) out.push(`- ${md(r.brand)} ${md(r.series)}: ${md(r.band)}`);
    out.push("", "</details>", "");
  }
  out.push("---", "", "© 2026 Square Smile Media / KlarFunk — wireless equipment frequency database, licensed under [CC BY 4.0](LICENSE). " +
    "When you reuse the data, give credit with this line, link to the license, and say if you changed it.", "");
  return out.join("\n");
}

function html() {
  const h = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  const rows = brands.flatMap(rowsOf).map((r) => {
    const s = src(r);
    const hay = [r.brand, r.series, r.band, range(r), r.note].join(" ").toLowerCase();
    const td = (label, v, cls) => `<td data-label="${label}"${cls ? ` class="${cls}"` : ""}>${v}</td>`;
    return `<tr data-q="${h(hay)}">` + td("Brand", h(r.brand)) + td("Series", h(r.series)) + td("Band", h(r.band)) +
      td("MHz", h(range(r)), "n") + td("Type", TYPES[r.deviceType]) + td("Step", h(step(r)), "n") +
      td("Source", s ? `<a href="${h(s.url)}" rel="noopener">${h(s.title)}</a>` : "") + td("Note", h(r.note)) + "</tr>";
  }).join("\n");
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Wireless Equipment List</title>
<meta name="description" content="Wireless mic, IEM and WMAS frequency ranges from ${brands.length} brands, each cited to the manufacturer's own document.">
<style>
:root{--bg:#fff;--fg:#1a1a1a;--mute:#666;--line:#e3e3e3;--head:#f6f6f6;--link:#0b5cad;--mark:#fff3b0}
@media (prefers-color-scheme:dark){:root{--bg:#141414;--fg:#e8e8e8;--mute:#9a9a9a;--line:#2c2c2c;--head:#1d1d1d;--link:#7fb6ff;--mark:#4a4000}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--fg);font:15px/1.45 system-ui,-apple-system,"Segoe UI",sans-serif}
main{max-width:1400px;margin:0 auto;padding:24px 16px 48px}h1{font-size:1.6rem;margin:0 0 4px}p{margin:6px 0;color:var(--mute)}
a{color:var(--link)}input{width:100%;max-width:520px;margin:16px 0 8px;padding:10px 12px;font:inherit;color:var(--fg);background:var(--bg);border:1px solid var(--line);border-radius:6px}
.wrap{overflow-x:auto;border:1px solid var(--line);border-radius:6px}table{border-collapse:collapse;width:100%;min-width:900px}
th,td{text-align:left;vertical-align:top;padding:6px 10px;border-bottom:1px solid var(--line)}th{position:sticky;top:0;background:var(--head);font-weight:600}
td.n{white-space:nowrap;font-variant-numeric:tabular-nums}td:nth-child(7){max-width:220px}td:nth-child(8){max-width:420px;color:var(--mute);font-size:.92em}
#count{font-size:.9em}tr[hidden]{display:none!important}td a{overflow-wrap:anywhere}
@media (max-width:700px){table,tbody{display:block;min-width:0;width:100%}td{overflow-wrap:anywhere}td.n{white-space:normal}thead{display:none}tr{display:block;padding:10px 12px;border-bottom:1px solid var(--line)}
td{display:block;border:0;padding:1px 0;max-width:none!important}td:empty{display:none}td::before{content:attr(data-label) ": ";color:var(--mute);font-size:.85em}
td:first-child,td:nth-child(2){display:inline;font-weight:600}td:first-child::before,td:nth-child(2)::before{content:""}td:first-child::after{content:" "}}
</style>
</head>
<body>
<main>
<h1>Wireless Equipment List</h1>
<p>List version <strong>${h(pkg.version)}</strong> · ${ranged.length} frequency bands and ${pkg.manufacturers.length - ranged.length} notes from ${brands.length} brands. Every range links to the manufacturer document it comes from.</p>
<p>A range is what the hardware can tune; whether you may use it depends on your country. Found an error? <a href="${REPO_URL}/issues/new">Open an issue</a> with a link to the manufacturer's document. Data: <a href="v1/rf-equipment.json">v1/rf-equipment.json</a> · <a href="${REPO_URL}">GitHub</a> · <a href="LICENSE">CC BY 4.0</a></p>
<input id="q" type="search" placeholder="Search brand, model, band or MHz (e.g. 606, ULXD, IEM)" aria-label="Search the equipment list" autofocus>
<p id="count"></p>
<div class="wrap"><table>
<thead><tr><th>Brand</th><th>Series</th><th>Band</th><th>MHz</th><th>Type</th><th>Step</th><th>Source</th><th>Note</th></tr></thead>
<tbody id="rows">
${rows}
</tbody></table></div>
<p>© 2026 Square Smile Media / KlarFunk — licensed under CC BY 4.0. When you reuse the data, give credit with this line, link to the license, and say if you changed it.</p>
</main>
<script>
(function () {
  var rows = Array.prototype.slice.call(document.querySelectorAll("#rows tr"));
  var q = document.getElementById("q"), count = document.getElementById("count");
  // A plain number also matches every range that contains it.
  function ranges(tr) {
    var t = tr.querySelector("[data-label=MHz]").textContent; if (!t) return [];
    return t.split(" + ").map(function (s) { var p = s.split("–"); return [parseFloat(p[0]), parseFloat(p[1])]; });
  }
  function run() {
    var terms = q.value.toLowerCase().trim().split(/\\s+/).filter(Boolean), shown = 0;
    rows.forEach(function (tr) {
      var ok = terms.every(function (t) {
        if (/^\\d+(\\.\\d+)?$/.test(t)) {
          var f = parseFloat(t);
          if (ranges(tr).some(function (r) { return f >= r[0] && f <= r[1]; })) return true;
        }
        return tr.getAttribute("data-q").indexOf(t) !== -1;
      });
      tr.hidden = !ok; if (ok) shown++;
    });
    count.textContent = shown + " of " + rows.length + " rows";
  }
  q.addEventListener("input", run); run();
})();
</script>
</body>
</html>
`;
}

const args = process.argv.slice(2);
if (args[0] === "--html") {
  if (!args[1]) { console.error("usage: build-list.mjs --html <path>"); process.exit(2); }
  writeFileSync(args[1], html());
  console.log("wrote " + args[1]);
} else if (args[0] === "--check") {
  let cur = "";
  try { cur = readFileSync(pathOf("EQUIPMENT.md"), "utf8"); } catch {}
  if (cur !== markdown()) {
    console.error("EQUIPMENT.md is out of date: run `node scripts/build-list.mjs` and commit it.");
    process.exit(1);
  }
  console.log("EQUIPMENT.md is up to date");
} else {
  writeFileSync(pathOf("EQUIPMENT.md"), markdown());
  console.log("wrote EQUIPMENT.md");
}
